#!/usr/bin/env python3
"""Build the presentation assets used by the independent SPIRA surfaces."""

import argparse
import json
from io import BytesIO
from pathlib import Path

DESIGN = Path(__file__).resolve().parent
FONTS = DESIGN / "fonts"
ROOT = DESIGN.parents[1]
APP = Path("app/lib")
HUB = Path("hub/spira_hub")
SIM = Path("simulator/spira_simulator")
HOUSE = SIM / "ui/house"


def read(name):
    return json.loads((DESIGN / name).read_text(encoding="utf-8"))


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def css_tokens(tokens):
    ease = ",".join(map(str, tokens["motion"]["ease"]))
    fonts = ", ".join(
        name if name == "sans-serif" else quoted(name)
        for name in [tokens["font"], *tokens["font-fallbacks"]]
    )
    values = {"color-scheme": "light"}
    values.update({f"--{key}": value for key, value in tokens["colors"].items()})
    for key, steps in (("radius", tokens["radii"].items()),
                       ("space", ((n, n) for n in tokens["spacing"])),
                       ("size", ((n, n) for n in tokens["type"]))):
        values.update({f"--{key}-{name}": f"{size}px" for name, size in steps})
    values.update({
        "--sans": fonts,
        "--ease": f"cubic-bezier({ease})",
        "--settle": f'{tokens["motion"]["settle-ms"]}ms',
    })
    return (
        "/* Generated by demo-shell/design/build.py from tokens.json. */\n:root {\n"
        + "".join(f"  {name}: {value};\n" for name, value in values.items())
        + "}\n"
    )


def camel(name):
    first, *rest = name.split("-")
    return first + "".join(part.capitalize() for part in rest)


def dart_tokens(tokens):
    ease = ", ".join(map(str, tokens["motion"]["ease"]))
    constants = [
        f"  static const {camel(name)} = Color(0xFF{value[1:].upper()});"
        for name, value in tokens["colors"].items()
    ]
    for prefix, steps in (("radius", tokens["radii"].items()),
                          ("space", ((n, n) for n in tokens["spacing"])),
                          ("size", ((n, n) for n in tokens["type"]))):
        constants += [
            f"  static const {prefix}{str(name).capitalize()} = {float(size)};"
            for name, size in steps
        ]
    constants += [
        f'  static const font = {quoted(tokens["font"])};',
        f"  static const ease = Cubic({ease});",
        f'  static const settle = Duration(milliseconds: {tokens["motion"]["settle-ms"]});',
    ]
    return (
        "// Generated by demo-shell/design/build.py from tokens.json.\n"
        "import 'dart:ui' show Color;\n\n"
        "import 'package:flutter/animation.dart' show Cubic;\n\n"
        "abstract final class DesignTokens {\n" + "\n".join(constants) + "\n}\n"
    )


def python_vocabulary(vocabulary):
    devices = vocabulary["devices"]
    tables = {
        "DEVICE_NAMES": {key: device.get("short", device["name"]) for key, device in devices.items()},
        "ROOM_NAMES": vocabulary["rooms"],
        "STATE_WORDS": vocabulary["states"],
    }
    return (
        '"""Generated by demo-shell/design/build.py from vocabulary.json."""\n\n'
        + "\n\n".join(f"{name} = {json.dumps(data, ensure_ascii=False, indent=4)}" for name, data in tables.items())
        + "\n"
    )


def js_vocabulary(vocabulary):
    tables = {
        "DEVICE_NAMES": {key: device["name"] for key, device in vocabulary["devices"].items()},
        "ROOM_NAMES": vocabulary["rooms"],
        "STATE_WORDS": vocabulary["states"],
        "LINE_WORDS": vocabulary["lines"],
        "END_WORDS": vocabulary["ends"],
        "VERDICT_WORDS": vocabulary["verdicts"],
    }
    return "// Generated by demo-shell/design/build.py from vocabulary.json.\n" + "".join(
        f"export const {name} = Object.freeze({json.dumps(data, ensure_ascii=False, indent=2)});\n"
        for name, data in tables.items()
    )


def dart_vocabulary(vocabulary):
    devices = vocabulary["devices"]
    tables = {
        "deviceNames": {key: quoted(device["name"]) for key, device in devices.items()},
        "appDeviceNames": {key: quoted(device["app-label"]) for key, device in devices.items() if "app-label" in device},
        "deviceIcons": {key: f'Icons.{device["icon"]}' for key, device in devices.items()},
        "roomNames": {key: quoted(value) for key, value in vocabulary["rooms"].items()},
        "stateWords": {key: quoted(value) for key, value in vocabulary["states"].items()},
        "lineWords": {key: quoted(value) for key, value in vocabulary["lines"].items()},
        "endWords": {key: quoted(value) for key, value in vocabulary["ends"].items()},
        "verdictWords": {key: quoted(value) for key, value in vocabulary["verdicts"].items()},
    }
    return (
        "// Generated by demo-shell/design/build.py from vocabulary.json.\n"
        "// ignore: deprecated_member_use\n"
        "import 'package:flutter/material.dart';\n\n"
        + "\n".join(
            f"const {name} = {{\n"
            + "".join(f"  {quoted(key)}: {value},\n" for key, value in table.items())
            + "};\n"
            for name, table in tables.items()
        )
    )


def web_fonts():
    from fontTools.ttLib.woff2 import compress

    files = {HOUSE / "fonts/LICENSE.txt": (FONTS / "LICENSE.txt").read_bytes()}
    for weight in ("Regular", "Medium", "SemiBold", "Bold"):
        name = f"IBMPlexSansKR-{weight}"
        output = BytesIO()
        compress(FONTS / f"{name}.otf", output)
        files[HOUSE / f"fonts/{name}.woff2"] = output.getvalue()
    return files


def generate():
    tokens = read("tokens.json")
    vocabulary = read("vocabulary.json")
    css = css_tokens(tokens)
    python = python_vocabulary(vocabulary)
    return {
        "app": {
            APP / "design_tokens.g.dart": dart_tokens(tokens),
            APP / "design_vocabulary.g.dart": dart_vocabulary(vocabulary),
        },
        "hub": {
            HUB / "dashboard_assets/tokens.css": css,
            HUB / "design_vocabulary.py": python,
        },
        "simulator": {
            HOUSE / "tokens.css": css,
            HOUSE / "vocabulary.js": js_vocabulary(vocabulary),
            SIM / "design_vocabulary.py": python,
        },
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check without writing")
    parser.add_argument("--part", choices=("app", "hub", "simulator"), help="limit to one part")
    args = parser.parse_args()
    outputs = generate()
    if args.part in (None, "simulator"):
        outputs["simulator"].update(web_fonts())
    stale = []
    for part, files in outputs.items():
        if args.part and part != args.part:
            continue
        for relative, contents in files.items():
            path = ROOT / relative
            data = contents.encode("utf-8") if isinstance(contents, str) else contents
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
            elif not path.is_file() or path.read_bytes() != data:
                stale.append(relative)
    if stale:
        for path in stale:
            print(f"Out of date: {path}")
        print("Regenerate with python3 demo-shell/design/build.py")
    return bool(stale)


if __name__ == "__main__":
    raise SystemExit(main())
